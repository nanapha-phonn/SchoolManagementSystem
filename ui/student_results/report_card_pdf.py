from pathlib import Path

from ui.transactions.pdf_export import export_text_pdf


def export_student_report_card_pdf(file_path, report):
    """Generate a printable PDF student report card."""

    if not isinstance(report, dict):
        raise ValueError("Invalid student report-card data.")

    student = report.get("student") or {}
    academic_year = report.get("academic_year") or {}
    assessment = report.get("assessment_period") or {}
    class_info = report.get("class") or {}
    section = report.get("section") or {}
    summary = report.get("summary") or {}
    subjects = report.get("subjects") or []

    if not student.get("admission_no"):
        raise ValueError("Student information is missing.")

    if not assessment.get("name"):
        raise ValueError("Assessment period information is missing.")

    lines = [
        f"Student Name: {student.get('full_name', '-')}",
        f"Admission Number: {student.get('admission_no', '-')}",
        f"Class: {class_info.get('name', '-')}",
        f"Section: {section.get('name', '-')}",
        f"Academic Year: {academic_year.get('name', '-')}",
        "",
        f"Assessment Period: {assessment.get('name', '-')}",
        f"Period Type: {assessment.get('type', '-')}",
        (
            f"Assessment Dates: {assessment.get('start_date', '-')}"
            f" to {assessment.get('end_date', '-')}"
        ),
        "",
        "=" * 65,
        "SUBJECT RESULTS",
        "=" * 65,
    ]

    if not subjects:
        lines.append("No subject results have been recorded.")
    else:
        for index, subject in enumerate(subjects, start=1):
            marks = float(subject["marks_obtained"])
            maximum = float(subject["maximum_marks"])

            percentage = subject.get("percentage")
            percentage_text = (
                f"{float(percentage):.2f}%"
                if percentage is not None else "-"
            )

            grade_point = subject.get("grade_point")
            grade_point_text = (
                f"{float(grade_point):g}"
                if grade_point is not None else "-"
            )

            lines.extend([
                f"{index}. {subject.get('subject_name', '-')}",
                f"   Subject Code: {subject.get('subject_code', '-')}",
                f"   Teacher: {subject.get('teacher_name', '-')}",
                f"   Marks: {marks:g} / {maximum:g}",
                f"   Percentage: {percentage_text}",
                f"   Grade: {subject.get('grade_label') or '-'}",
                f"   Grade Point: {grade_point_text}",
                f"   Remark: {subject.get('grade_remark') or '-'}",
                "",
            ])

    lines.extend([
        "=" * 65,
        "OVERALL SUMMARY",
        "=" * 65,
        f"Subjects: {summary.get('subject_count', 0)}",
        (
            f"Total Marks: "
            f"{summary.get('total_marks_obtained', 0)} / "
            f"{summary.get('total_maximum_marks', 0)}"
        ),
    ])

    overall_percentage = summary.get("overall_percentage")
    lines.append(
        "Overall Percentage: "
        + (
            f"{float(overall_percentage):.2f}%"
            if overall_percentage is not None else "-"
        )
    )

    lines.append(
        f"Overall Grade: {summary.get('overall_grade_label') or '-'}"
    )

    grade_point = summary.get("overall_grade_point")
    lines.append(
        "Overall Grade Point: "
        + (
            f"{float(grade_point):g}"
            if grade_point is not None else "-"
        )
    )

    lines.append(
        f"Overall Remark: {summary.get('overall_remark') or '-'}"
    )

    grading_scheme = report.get("grading_scheme")
    if grading_scheme:
        lines.extend([
            "",
            (
                f"Grading Scheme: {grading_scheme.get('name', '-')}"
                f" | Version {grading_scheme.get('version', '-')}"
            ),
        ])

    lines.extend([
        "",
        "Generated by School Management System",
    ])

    output_path = Path(file_path)

    return export_text_pdf(
        output_path,
        "STUDENT REPORT CARD",
        "\n".join(lines),
    )
